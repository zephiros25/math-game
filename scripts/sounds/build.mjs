// The game's default sounds, made in the Studio's Sounds page, live in
// assets/sounds/default-set/ with a sounds.json listing them per slot:
//   { "tap": { "files": ["tap-1.wav", ...], "volume": 1 }, ..., "voice": {...} }
// This generates src/default-sounds.generated.ts with static require() calls.
// Slots without a file keep using the built-in synthesized sounds.
//
// Run with: npm run sounds   (also runs before `npm start` and whenever the
// Studio changes a default sound)

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const DEFAULT_SET_DIR = fileURLToPath(new URL('../../assets/sounds/default-set/', import.meta.url));
export const DEFAULT_SLOTS = ['tap', 'backspace', 'button', 'correct', 'wrong', 'levelUp', 'fanfare', 'coin', 'gem', 'voice'];
const outFile = fileURLToPath(new URL('../../src/default-sounds.generated.ts', import.meta.url));

export function readDefaultSet() {
  const file = join(DEFAULT_SET_DIR, 'sounds.json');
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {};
}

export function buildDefaultSounds({ quiet = false } = {}) {
  const set = readDefaultSet();
  const lines = [];
  for (const slot of DEFAULT_SLOTS) {
    const files = (set[slot]?.files ?? []).filter((f) => existsSync(join(DEFAULT_SET_DIR, f)));
    if (!files.length) continue;
    const sources = files.map((f) => `require('../assets/sounds/default-set/${f}')`).join(', ');
    lines.push(`  ${slot}: { sources: [${sources}], volume: ${set[slot].volume ?? 1} },`);
  }
  const content = `// Generated by scripts/sounds/build.mjs from assets/sounds/default-set/sounds.json. Do not edit.
// Default sounds made in the Studio; slots left out use the built-in sounds.

import type { DefaultSetSlot } from './feedback';

export const DEFAULT_SET: Partial<Record<DefaultSetSlot, { sources: number[]; volume: number }>> = {
${lines.join('\n')}
};
`;
  const old = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (old !== content) writeFileSync(outFile, content);
  if (!quiet) console.log(`Default sounds: ${lines.length} of ${DEFAULT_SLOTS.length} slots made in the Studio`);
  return { slots: lines.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) buildDefaultSounds();
