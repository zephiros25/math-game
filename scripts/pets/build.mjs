// Validates every pet in pets/ and generates src/pet-registry.generated.ts,
// which the app imports (static require() calls so the bundler picks up the
// pictures and voices).
//
// Run with: npm run pets   (also runs before `npm start` and whenever the
// Studio saves a pet)

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PETS_DIR, validatePet } from './schema.mjs';

const petsDir = fileURLToPath(PETS_DIR);
const outFile = fileURLToPath(new URL('../../src/pet-registry.generated.ts', import.meta.url));

export function loadPets() {
  const pets = [];
  const errors = [];
  const warnings = [];
  const ids = existsSync(petsDir)
    ? readdirSync(petsDir, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith('.')).map((d) => d.name)
    : [];
  for (const id of ids) {
    const dir = join(petsDir, id);
    const file = join(dir, 'pet.json');
    if (!existsSync(file)) {
      warnings.push(`${id}: no pet.json, skipped`);
      continue;
    }
    let json;
    try {
      json = JSON.parse(readFileSync(file, 'utf8'));
    } catch (e) {
      errors.push(`${id}: pet.json is not valid JSON (${e.message})`);
      continue;
    }
    const result = validatePet(id, json, dir);
    errors.push(...result.errors);
    warnings.push(...result.warnings);
    if (result.errors.length === 0) pets.push({ id, ...json });
  }
  pets.sort((a, b) => a.order - b.order || a.name.localeCompare(b.name));
  return { pets, errors, warnings };
}

// require() calls are written as placeholders, then unquoted after JSON.stringify.
const req = (id, file) => (file ? `@@require('../pets/${id}/${file}')@@` : null);

function toData(p) {
  const { images, voice, ...meta } = p;
  return {
    ...meta,
    idle: req(p.id, images.idle),
    blink: req(p.id, images.blink),
    talk: req(p.id, images.talk),
    voicePitch: voice.pitch,
    voiceVolume: voice.volume,
    voiceFiles: voice.files.map((f) => req(p.id, f)),
    lines: p.lines ?? {},
  };
}

function render(pets) {
  const body = JSON.stringify(pets.map(toData), null, 2).replace(/"@@(.*?)@@"/g, '$1');
  return `// GENERATED by scripts/pets/build.mjs from the pets/ folder. Do not edit:
// change pets in the Studio (npm run studio, then "Pets") or edit pets/*/pet.json.

import type { PetData } from './pets';

export const PET_DATA: PetData[] = ${body};
`;
}

export function buildPets({ quiet = false } = {}) {
  // Pets with errors are left out; the rest still build.
  const { pets, errors, warnings } = loadPets();
  const next = render(pets);
  const prev = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (next !== prev) writeFileSync(outFile, next);
  if (!quiet) {
    for (const w of warnings) console.warn(`  ⚠ ${w}`);
    for (const e of errors) console.error(`  ✖ ${e}`);
    console.log(`Built ${pets.length} pets${errors.length ? ' (pets with errors were left out)' : ''}.`);
  }
  return { pets, errors, warnings };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { errors } = buildPets();
  process.exitCode = errors.length ? 1 : 0;
}
